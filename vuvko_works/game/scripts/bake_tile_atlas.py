def load_wanted(index: Path, taxonomy: Path) -> list[str]:
    """Every tile the game can actually put on a deck.

    Read the built index rather than the taxonomy. The taxonomy is every tile
    that was *classified*, which is neither what ships nor what can be placed:
    it still contains the fuel intakes the generator is told to avoid, and it
    contains no overlays at all, because an overlay has no geometry to classify
    and is only ever drawn over a base. Baking the taxonomy therefore shipped
    195 tiles nothing would ever ask for and left out the 453 that hold the
    furniture.
    """
    if index.exists():
        doc = json.loads(index.read_text())
        return sorted(tile["path"] for tile in doc["tiles"])

    doc = json.loads(taxonomy.read_text())
    tiles = doc["tiles"] if isinstance(doc, dict) and "tiles" in doc else doc
    return sorted(tiles)


def human(size: int) -> str:
    if size > 1_000_000:
        return f"{size / 1_000_000:.1f} MB"
    return f"{size / 1000:.0f} KB"


def main() -> None:
    here = Path(__file__).resolve().parent
    root = here.parent
    shared = root.parent

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tiles", type=Path, default=shared / "geomorphs")
    parser.add_argument("--taxonomy", type=Path, default=shared / "tiles.taxonomy.json")
    parser.add_argument(
        "--index", type=Path, default=root / "src" / "assets" / "tiles" / "manifest.json"
    )
    parser.add_argument("--out", type=Path, default=root / "public" / "geomorphs")
    parser.add_argument("--px-per-foot", type=float, default=4.0)
    parser.add_argument("--quality", type=int, default=60)
    parser.add_argument("--limit", type=int, default=0, help="stop after N tiles, for a quick look")
    args = parser.parse_args()

    if not args.tiles.exists():
        sys.exit(
            f"No tile library at {args.tiles}.\n"
            "It is fetched, not committed: cd .. && python3 fetch_geomorphs.py"
        )

    wanted = load_wanted(args.index, args.taxonomy)
    if args.limit:
        wanted = wanted[: args.limit]

    if args.out.exists():
        shutil.rmtree(args.out)
    args.out.mkdir(parents=True)

    scale = args.px_per_foot / SOURCE_PX_PER_FOOT
    written = 0
    missing = 0
    total = 0

    for relative in wanted:
        source = args.tiles / relative
        if not source.exists():
            missing += 1
            continue
        image = Image.open(source).convert("RGBA")
        size = (max(1, round(image.width * scale)), max(1, round(image.height * scale)))
        image = image.resize(size, Image.LANCZOS)

        target = (args.out / relative).with_suffix(".webp")
        target.parent.mkdir(parents=True, exist_ok=True)
        image.save(target, "WEBP", quality=args.quality, method=5)
        total += target.stat().st_size
        written += 1
        if written % 200 == 0:
            print(f"  {written}/{len(wanted)}  {human(total)}", flush=True)

    # What the renderer needs to know about this bake. Assuming the source
    # resolution is exactly the bug this file exists to prevent: a downscaled
    # tile read as full resolution draws at a fraction of its size.
    (args.out / "atlas.json").write_text(
        json.dumps(
            {
                "pxPerFoot": args.px_per_foot,
                "sourcePxPerFoot": SOURCE_PX_PER_FOOT,
                "bleedFeet": 10,
                "tiles": written,
                "format": "webp",
            },
            indent=2,
        )
        + "\n"
    )

    (args.out / "README.md").write_text(
        README.format(
            source=SOURCE_PX_PER_FOOT,
            target=args.px_per_foot,
            count=written,
            size=human(total),
        )
    )
    (args.out / "LICENCE.md").write_text(LICENCE)

    print(f"{written} tiles -> {args.out}  ({human(total)})")
    if missing:
        print(f"{missing} classified tiles were not on disk")


if __name__ == "__main__":
    main()
