#!/usr/bin/env python3
"""
Bake a downscaled tile set the game can ship.

The map generator can place any tile the taxonomy classified, so a build that
generates ships cannot get away with copying the handful one deck happens to
use. The whole classified set at source resolution is far too large to ship —
but it does not need to be: the tiles are drawn under the hex lattice, blurred
and held at low opacity, where a fraction of the detail survives anyway.

This writes a separate, downscaled *version* of the artwork. It is a derivative
work, so it carries its own notice: see the README.md and LICENCE.md written
alongside it.

**Four pixels to the foot is not an arbitrary default.** Map generation
rasterises a hull at exactly that, so at 4 px/ft the tiles go down one for one
with no resampling, and the rooms that come out match the source artwork
exactly. Measured on one ship: 4 px/ft finds the same 26 compartments and the
same 44,810 sq ft of floor as the full-resolution art, while 3 px/ft finds 33
and 2 px/ft finds 53 — thin walls go sub-pixel, smear, and cut rooms in half.
It is resolution that does this, not compression: lossless at 2 px/ft is no
better than quality 70.

    python3 scripts/bake_tile_atlas.py            # default 3 px per foot
    python3 scripts/bake_tile_atlas.py --px-per-foot 2 --quality 70
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

try:
    from PIL import Image
except ImportError:  # pragma: no cover
    sys.exit("Pillow is required: pip install pillow")

SOURCE_PX_PER_FOOT = 12

README = """# Downscaled geomorph tiles

**This is not the original artwork.** It is a reduced-resolution derivative,
generated by `scripts/bake_tile_atlas.py`, and it exists only so a built game
can draw a ship's deck plan without shipping the full library.

- **Original:** Starship Geomorphs / RPG Mobius Geomorphs, by Robert Pearce,
  screen colouring by Eric B. Smith — <https://rpgmobius.com/geomorphs>
- **Licence:** Creative Commons Attribution-NonCommercial 4.0 International
  (CC BY-NC 4.0). See [LICENCE.md](LICENCE.md).
- **Changes made:** downscaled from {source} px per foot to {target} px per
  foot and re-encoded as WebP with an alpha channel. Nothing else — no
  recolouring, no cropping, no rearrangement.

The full-resolution library is **not** committed anywhere in this repository.
Fetch it yourself with `vuvko_works/fetch_geomorphs.py`, then run the bake
script to regenerate this folder.

Anything built with these tiles has to stay **non-commercial**.

{count} tiles, {size}. Regenerate with:

```
python3 scripts/bake_tile_atlas.py
```
"""

