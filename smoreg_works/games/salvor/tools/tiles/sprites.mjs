/**
 * Every icon in the game, as data.
 *
 * A sprite is twelve strings of twelve characters — a mask, not an image, and a
 * mask with exactly two states:
 *
 *   #  ink — this pixel belongs to the figure
 *   .  hole — this pixel is not there
 *
 * There is no second tone and there is no colour. Both were here and both came
 * out (`docs/gui-guides.md`, §6.2 and §6.4, off Kyzrati's nine years of running
 * ASCII and tiles side by side): a shade that is two steps off the main colour
 * is invisible at 12 px and pure noise on a crowded schematic, and colour on a
 * map has to carry state — whose it is, how hurt it is, whether the door will
 * open — so art that spends colour on itself has spent the map's only signal.
 * A lens is therefore a hole in the silhouette rather than a lighter patch, and
 * the amber that marked a lock and a relic is gone from the art entirely: amber
 * is a state, and a state is worn by the frame the view draws around a tile.
 *
 * What the tile is painted in is decided outside this file — by the game's own
 * tables at build time for the atlas (`content.mjs` reads a machine's `fg` and a
 * door state's palette entry), and by `currentColor` for the SVG symbols, which
 * is the whole reason they can be recoloured by the view at all.
 *
 * The rest of the rules, same source: one silhouette per tile, read at a glance
 * against a dark hull; a solid figure with a thick edge, because tiles have to
 * stay apart in a dense group and a thin line closes up; no anti-aliasing, so a
 * tile at 1× is the tile at 4×; and nothing decorative — a pixel is in a sprite
 * because it separates that icon from another one.
 *
 * Whole families share a skeleton on purpose, and that is §6.5: what has to be
 * read first is "machine / thing / system", and only then which machine. So
 * every machine is a chassis with eye holes, every door is the same frame with
 * a different leaf, every relic carries the same two-by-two block in the corner.
 * The ghost is the drone's outline with the inside taken out, because that is
 * what it is.
 */

